"""OperationalChainService: the signed, hash-chained record of a revision's
*operational* lifecycle -- freshness basis, legal hold, retention floor --
and the append that makes every transition provable after the fact rather
than merely stored.

Mirrors `receipt.py`'s own chain (`arc_receipt_events`/`arc_receipt_event_
heads`) in shape -- a locked head row makes append O(1), a genesis event at
sequence 0 has no predecessor, every later event's digest covers its
predecessor's -- but this is a *second*, independent chain keyed by
`revision_id`, not `receipt_id`. A revision's operational chain outlives
any one resolution and is the thing every later resolution's mandatory-
serving check will eventually have to trust (wiring that trust in is
`registry.arc.service.integrity`'s job, not this module's -- see the
class docstring below).

**Every append writes three rows in the caller's own transaction: the
event, the advanced head, and a pending checkpoint outbox row.** The
database transaction that writes the event also writes the head and the
pending checkpoint -- never one without the other two. Nothing here opens
a session -- `append_event` takes the caller's own session so the
operational write commits atomically with whatever domain change it is
evidence of (a submitted proposal's genesis event alongside its draft
revision, a source revocation's cascade alongside the source-status flip
it is evidence of).

**Signing.** Every event's raw digest is signed under a domain-separated
tag, the same shape a deployment's receipt-signing key already uses for
its own purpose. This module does not reach into `signing.py`'s
`ReceiptSigningProvider`, because every purpose that provider serves is
gated behind operator-configured key material this deployment does not
have yet (`services.py`'s own `arc_signing_keys = {}`) -- reusing that gate
here would mean this service, and therefore `SourceStatusService`'s
revocation/expiry cascade injected on top of it, could never actually
append anything on any deployment that exists today. Instead this module
generates its own Ed25519 keypair once per process (`_process_signing_key`,
cached) and signs with it directly. Private key material never leaves
process memory and is never persisted to any table -- but it also does not
survive a restart or scale past one process, which is a real production
gap, not a hidden one: a deployment that needs rotation, multi-process
consistency, or HSM/KMS custody for this signature needs the same kind of
operator-configured key material every other ARC signing purpose is
already waiting on, and wiring that in is a follow-up, not something this
task invents a shape for. `_register_public_key` keeps every key this
process has ever signed with (not just the current one) resolvable by
`verify_chain`, so a key generated by one wiring call site
(`wiring/services.py`) can still verify a chain another call site
(`wiring/jobs.py`) extended -- see both modules' own comments for why two
call sites exist at all.
"""

